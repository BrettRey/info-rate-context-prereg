"""F2's report: f2_report.md from f2_summary.tsv, f2_oracle.tsv and f2_oracle_check.tsv (every number copied from them).

When f2_neural.tsv (the neural subset, from the HF job) is present, each fit is joined with its KenLM cell's
escape bits (same pooling, checked by count), written to f2_neural_summary.tsv and tabled beside the oracle.

Usage: python -I src/fakedata/f2_report.py OUT_DIR
"""
import csv
import sys
from pathlib import Path

NAMES = {"R1": "pairs", "R2": "partial merge", "R3": "deletion"}


def read(path):
    return list(csv.DictReader(open(path), delimiter="\t"))


NEURAL_FIELDS = ["proc", "R", "line", "budget", "k", "comparison", "k_fine", "span_mean", "n_seeds", "oracle_fine",
                 "oracle_coarse", "neural_fine", "neural_coarse", "neural_coarse_sd", "kenlm_fine", "kenlm_coarse",
                 "convention_pct", "neural_total_pct", "kenlm_total_pct", "pooled_share"]


def neural(out_dir):
    """Join the neural fits with the KenLM cells' escape bits and the oracle; None if no neural results."""
    path = out_dir / "f2_neural.tsv"
    if not path.exists():
        return None
    orc = {(r["proc"], r["R"], int(r["line"]), int(r["k"])): r for r in read(out_dir / "f2_oracle.tsv")}
    esc, ken = {}, {}
    for frag in (out_dir / "cells").glob("*.tsv"):
        for r in read(frag):
            key = (r["proc"], r["R"], int(r["line"]), int(r["budget"]), int(r["seed"]))
            esc[key] = (float(r["escape_bits"]), int(r["n_pooled_test"]), int(r["n_coarse_test"]))
            ken.setdefault(key[:4] + (int(r["k"]),), []).append(float(r["corrected_escape"]))
    fits = {}
    for r in read(path):
        if r.get("error"):
            continue
        key = (r["proc"], r["R"], int(r["line"]), int(r["budget"]), int(r["seed"]))
        escape, n_pooled, n_coarse = esc[key]
        if int(r["n_pooled_test"]) != n_pooled or int(r["n_test"]) != n_coarse:
            raise ValueError(f"neural and KenLM pooling disagree for {key}")
        corrected = (float(r["test_bits"]) * int(r["n_test"]) + escape) / int(r["n_fine_test"])
        fits.setdefault(key[:4] + (int(r["k"]),), []).append((corrected, n_pooled / n_coarse))
    rows = []
    for (name, R, line, budget, k), vals in sorted(fits.items()):
        if R == "R0":
            continue
        o = orc[(name, R, line, k)]
        span = float(o["span_mean"])
        coarse = [v for v, _ in vals]
        for comparison, kf in (("same_k", k), ("matched_span", int(round(span)))):
            fine = fits.get((name, "R0", line, budget, kf))
            if not fine:
                continue
            of, oc = float(orc[(name, "R0", line, kf)]["corrected"]), float(o["corrected"])
            nf, nc = sum(v for v, _ in fine) / len(fine), sum(coarse) / len(coarse)
            kf_k = ken.get((name, "R0", line, budget, kf)); kc_k = ken.get((name, R, line, budget, k))
            sd = (sum((v - nc) ** 2 for v in coarse) / (len(coarse) - 1)) ** 0.5 if len(coarse) > 1 else ""
            rows.append(dict(proc=name, R=R, line=line, budget=budget, k=k, comparison=comparison, k_fine=kf,
                             span_mean=span, n_seeds=len(coarse), oracle_fine=round(of, 5), oracle_coarse=round(oc, 5),
                             neural_fine=round(nf, 5), neural_coarse=round(nc, 5),
                             neural_coarse_sd=round(sd, 5) if sd != "" else "",
                             kenlm_fine=round(sum(kf_k) / len(kf_k), 5) if kf_k else "",
                             kenlm_coarse=round(sum(kc_k) / len(kc_k), 5) if kc_k else "",
                             convention_pct=round(100 * (oc - of) / of, 2), neural_total_pct=round(100 * (nc - of) / of, 2),
                             kenlm_total_pct=round(100 * (sum(kc_k) / len(kc_k) - of) / of, 2) if kc_k else "",
                             pooled_share=round(vals[0][1], 4)))
    with open(out_dir / "f2_neural_summary.tsv", "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=NEURAL_FIELDS, delimiter="\t")
        wr.writeheader(); wr.writerows(rows)
    return rows


def main(out_dir):
    out_dir = Path(out_dir)
    rows = read(out_dir / "f2_summary.tsv")
    codes = sorted({r["code"] for r in read(out_dir / "f2_oracle.tsv")})
    out = ["# F2: the matched-count correction under regrouping", "",
           f"Generated by `src/fakedata/f2_report.py` from `f2_summary.tsv` (F2 code {', '.join(codes)}). Densities in "
           "bits per fine unit. Oracle: exact, given the context KenLM sees (R3 ignores the line end). KenLM: "
           "escape-coded (main analysis), mean over the seeds. Convention = oracle coarse minus oracle fine; total = "
           "KenLM coarse minus oracle fine, which includes estimation, pooling and spelling; both as % of the oracle "
           "fine density. Pooled = share of coarse test units pooled as `<rare>`. No pass/fail bar.", ""]
    for budget in sorted({int(r["budget"]) for r in rows}, reverse=True):
        for comparison, title in (("same_k", "same nominal k"), ("matched_span", "matched span")):
            out += [f"## {budget // 1_000_000}M units, {title}", "",
                    "| process | regrouping | line | k | fine k | span | oracle fine | oracle coarse | convention % | "
                    "KenLM fine | KenLM coarse | total % | pooled |",
                    "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
            for r in rows:
                if int(r["budget"]) != budget or r["comparison"] != comparison:
                    continue
                out.append(f"| {r['proc']} | {NAMES[r['R']]} | {r['line']} | {r['k']} | {r['k_fine']} | "
                           f"{float(r['span_mean']):.2f} | {float(r['oracle_fine']):.4f} | {float(r['oracle_coarse']):.4f} | "
                           f"{float(r['convention_pct']):+.2f} | {float(r['kenlm_fine']):.4f} | "
                           f"{float(r['kenlm_coarse']):.4f} | {float(r['total_pct']):+.2f} | "
                           f"{float(r['pooled_share_coarse']):.3f} |")
            out.append("")
    nrows = neural(out_dir)
    if nrows:
        for comparison, title in (("same_k", "same nominal k"), ("matched_span", "matched span")):
            out += [f"## Neural subset, 8M units, {title}", "",
                    "Production's neural estimator (`zero_unigram_cosine5`), escape-coded like KenLM, mean over the seeds "
                    "(`f2_neural_summary.tsv`). Fine k limited to the fitted 1, 2 and 4.", "",
                    "| process | regrouping | line | k | fine k | span | oracle fine | oracle coarse | convention % | "
                    "neural fine | neural coarse | neural total % | KenLM total % | pooled |",
                    "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
            for r in nrows:
                if r["comparison"] != comparison:
                    continue
                kt = f"{r['kenlm_total_pct']:+.2f}" if r["kenlm_total_pct"] != "" else ""
                out.append(f"| {r['proc']} | {NAMES[r['R']]} | {r['line']} | {r['k']} | {r['k_fine']} | {r['span_mean']:.2f} | "
                           f"{r['oracle_fine']:.4f} | {r['oracle_coarse']:.4f} | {r['convention_pct']:+.2f} | "
                           f"{r['neural_fine']:.4f} | {r['neural_coarse']:.4f} | {r['neural_total_pct']:+.2f} | {kt} | "
                           f"{r['pooled_share']:.3f} |")
            out.append("")
    check = out_dir / "f2_oracle_check.tsv"
    if check.exists():
        diffs = [float(r["diff"]) for r in read(check)]
        out += ["## Oracle check", "",
                f"Oracle cross-entropy minus plug-in conditional entropy on 10M simulated units, four types, lags 0–2 "
                f"(`f2_oracle_check.tsv`): minimum {min(diffs):+.5f}, maximum {max(diffs):+.5f} bits.", ""]
    (out_dir / "f2_report.md").write_text("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
