def balanced_shape():
    languages=np.unique(D.O.panel()[0])
    return (np.repeat(languages,150),
            np.array([f'{language}-s{speaker}' for language in languages for speaker in range(10) for _ in range(15)]),
            np.tile(np.arange(15).astype(str),len(languages)*10))


def scorer_probabilities(densities,p=.03):
    """Choose valid frozen Bernoulli scorers with exactly these cross-entropies."""
    h=lambda q:-(1-p)*np.log2(1-q)-p*np.log2(q)
    values=np.asarray(densities,float)
    if np.any(values<=h(p)):
        raise ValueError('requested density below the two-type process entropy')
    return np.array([brentq(lambda q:h(q)-density,p,1-1e-10,xtol=1e-14) for density in values.ravel()]).reshape(values.shape)


def corpora(languages,densities,rng,n_docs=16,p=.03,concentration=80,aligned=False,plugin=False):
    """Invented s0/s1 token losses under fixed models; actual document counts."""
    probabilities=scorer_probabilities(densities,p)
    shared=rng.beta(p*concentration,(1-p)*concentration,n_docs) if aligned else None
    records=[]
    for l,language in enumerate(languages):
        lengths=rng.integers(120,481,n_docs)
        ps=shared if aligned else rng.beta(p*concentration,(1-p)*concentration,n_docs)
        # Binomial counts are sufficient statistics of the generated fake tokens.
        ones=rng.binomial(lengths,ps)
        q=probabilities[l]
        losses=-(lengths-ones)[:,None]*np.log2(1-q)-ones[:,None]*np.log2(q)
        docs=[f'd{d}' for d in range(n_docs)]
        scores={rung:dict(id_bits=float(losses[:,k].sum()/lengths.sum()),n_test=int(lengths.sum()),
                    density_source='heldout_model',documents=[dict(document=doc,n_tokens=int(n),loss_sum_bits=float(loss))
                    for doc,n,loss in zip(docs,lengths,losses[:,k])]) for k,rung in enumerate(RUNGS)}
        if plugin:
            scores['1w'].update(id_bits=float(densities[l,0]),density_source='training_plugin')
        meta=dict(language=language,documents=dict(train=['fixed-train'],validation=['fixed-val'],test=docs))
        if aligned:
            meta['document_alignment']=dict(group='invented-translations',source_units={doc:doc for doc in docs})
        records.append(dict(job_id=language,metadata=meta,scores=scores))
    return records,probabilities


def markov_corpora(languages,flip_probabilities,known,rng,n_docs=16,aligned=False,plugin=False):
    """Exact likelihoods of stationary symmetric binary Markov text.

    Word length two: 1w ignores each word-initial predecessor and scores it at
    1 bit, then uses the correct transition for the continuation. Rungs 1/4
    use the correct transition except the first token of each document (1 bit).
    Corpus draws contain the same actual transitions at all three rungs.
    """
    shared_lengths=2*rng.integers(60,241,n_docs) if aligned else None
    uniforms=[rng.random(int(n)-1) for n in shared_lengths] if aligned else None
    records=[]
    for l,language in enumerate(languages):
        lengths=shared_lengths if aligned else 2*rng.integers(60,241,n_docs)
        eps=flip_probabilities[l]
        losses=[]
        for d,n in enumerate(lengths):
            # These are sufficient statistics of invented s0/s1 Markov tokens,
            # generated by XORing transitions onto a stationary Bernoulli(.5) start.
            flip=(uniforms[d] if aligned else rng.random(int(n)-1))<eps
            transition=np.where(flip,-np.log2(eps),-np.log2(1-eps))
            within=float(n/2+transition[::2].sum())
            plain=float(1+transition.sum())
            losses.append([within,plain,plain])
        losses=np.array(losses); docs=[f'd{d}' for d in range(n_docs)]
        scores={rung:dict(id_bits=float(losses[:,k].sum()/lengths.sum()),n_test=int(lengths.sum()),
                  density_source='heldout_model',documents=[dict(document=doc,n_tokens=int(n),loss_sum_bits=float(loss))
                  for doc,n,loss in zip(docs,lengths,losses[:,k])]) for k,rung in enumerate(RUNGS)}
        if plugin:
            scores['1w'].update(id_bits=float(known[l,0]),density_source='training_plugin')
        meta=dict(language=language,documents=dict(train=['fixed-train'],validation=['fixed-val'],test=docs))
        if aligned:
            meta['document_alignment']=dict(group='invented-translations',source_units={doc:doc for doc in docs})
        records.append(dict(job_id=language,metadata=meta,scores=scores))
    return records


def evaluate(n_rep=200,n_boot=1000,n_docs=16,seed=202610101103,shape=None,progress=None):
    if min(n_rep,n_boot,n_docs)<2:
        raise ValueError('at least two replicates, draws and documents required')
    shape=D.O.panel() if shape is None else shape
    languages=np.unique(shape[0]); n_language=len(languages)
    latent=np.linspace(1.6,2.1,n_language)
    residual=.025*np.sin(np.arange(n_language))
    rows=[]
    cases=(('reading_and_documents',False,False,False),
           ('documents_only',True,False,False),
           ('aligned_documents',False,True,False),
           ('training_plugin_1w',False,False,True))
    parameters=D.SETTINGS['data']
    for scenario,elasticity in SCENARIOS.items():
        entropies=np.exp(np.log(.65)+(residual if elasticity else 0)-elasticity*(latent-latent.mean()))
        entropy=lambda p: -p*np.log2(p)-(1-p)*np.log2(1-p)
        eps=np.array([brentq(lambda p:entropy(p)-h,1e-10,.5,xtol=1e-14) for h in entropies])
        # Token-weighted expected losses over the document-length population:
        # mean document length is exactly 300; document contexts always reset.
        plain=(1+299*entropies)/300
        densities=np.column_stack(((1+entropies)/2,plain,plain))
        true,quantities=A.paired_values(A.ladder(np.log(densities),latent)[0],RUNGS)
        for case,zero,aligned,plugin in cases:
            estimates=[]; bounds=[]; reading_errors=[]; document_errors=[]; tokens=[]; draw_audits=[]
            for rep in range(n_rep):
                # Independent reading/corpus/draw namespaces. Never reuse calibration-selection draws.
                local_seed=np.random.SeedSequence([seed,list(SCENARIOS).index(scenario),list(c[0] for c in cases).index(case),rep])
                reading_seed,corpus_seed,bootstrap_seed=local_seed.spawn(3)
                sr=np.exp(D.O.readings(latent,*shape,np.random.default_rng(reading_seed),zero,
                    **{key:parameters[key] for key in ('sd_speaker','sd_text','sd_language_text','sd_reading')}))
                _,means=A.language_means(shape[0],shape[1],sr)
                records=markov_corpora(languages,eps,densities,np.random.default_rng(corpus_seed),n_docs,aligned=aligned,plugin=plugin)
                ids=np.array([[r['scores'][k]['id_bits'] for k in RUNGS] for r in records])
                point,_=A.paired_values(A.ladder(np.log(ids),np.log(means))[0],RUNGS)
                observed_true,_=A.paired_values(A.ladder(np.log(densities),np.log(means))[0],RUNGS)
                draw_seed=int(bootstrap_seed.generate_state(1,dtype=np.uint64)[0])
                samples,_=A.resample_document_scores(records,n_boot,draw_seed)
                doc_ids=np.stack([samples[language] for language in languages],axis=1)
                try:
                    boot,draw_audit=A.panel_bootstrap(*shape,sr,np.log(ids),languages,n_boot,draw_seed,
                                                     document_samples=doc_ids,include_audit=True)
                except ValueError as error:
                    contextual=ValueError(f'{scenario}/{case}, replicate={rep}, seed={draw_seed}: {error}')
                    contextual.audit=getattr(error,'audit',None)
                    raise contextual from error
                boot,_=A.paired_values(boot,RUNGS)
                lo,hi=A.panel_interval(point,boot)
                estimates.append(point); bounds.append([lo,hi])
                draw_audits.append(draw_audit)
                reading_errors.append(observed_true-true); document_errors.append(point-observed_true)
                tokens.append(sum(r['scores']['1w']['n_test'] for r in records))
            estimates=np.array(estimates); bounds=np.array(bounds)
            covered=(bounds[:,0]<=true)&(true<=bounds[:,1])
            errors=estimates-true
            for q,name in enumerate(quantities):
                coverage=float(covered[:,q].mean())
                rows.append(dict(scenario=scenario,case=case,quantity=name,truth=float(true[q]),method=A.PANEL_METHOD,
                    nominal=.9,coverage=coverage,coverage_mcse=float(np.sqrt(coverage*(1-coverage)/n_rep)),
                    bias=float(errors[:,q].mean()),bias_mcse=float(errors[:,q].std(ddof=1)/np.sqrt(n_rep)),
                    rmse=float(np.sqrt(np.mean(errors[:,q]**2))),width=float(np.mean(bounds[:,1,q]-bounds[:,0,q])),
                    observed_minus_latent=float(np.mean(reading_errors,axis=0)[q]),
                    observed_minus_latent_mcse=float(np.std(reading_errors,axis=0,ddof=1)[q]/np.sqrt(n_rep)),
                    finite_test_minus_observed=float(np.mean(document_errors,axis=0)[q]),
                    n_rep=n_rep,n_boot=n_boot,n_docs=n_docs,n_languages=n_language,clusters=10,
                    n_readings=len(shape[0]),
                    requested_draws=sum(a['requested_draws'] for a in draw_audits),
                    usable_draws=sum(a['usable_draws'] for a in draw_audits),
                    undefined_draws=sum(a['undefined_draws'] for a in draw_audits),
                    max_undefined_draws=max(a['undefined_draws'] for a in draw_audits),
                    mean_test_tokens=float(np.mean(tokens)),training_fixed=True,aligned=aligned,plugin_1w=plugin,
                    below_nominal=coverage<.9,failed_original_84_screen=coverage<.84))
            if progress:
                progress(f'{scenario} {case}: '+', '.join(f'{quantities[q]}={covered[:,q].mean():.3f}' for q in range(len(quantities)))+
                         f"; undefined_draws={sum(a['undefined_draws'] for a in draw_audits)}/{n_rep*n_boot}")
    return rows


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('out',type=Path); parser.add_argument('--n-rep',type=int,default=200)
    parser.add_argument('--n-boot',type=int,default=1000); parser.add_argument('--n-docs',type=int,default=16)
    parser.add_argument('--seed',type=int,default=202610101103)
    parser.add_argument('--reading-shape',choices=('observed','balanced'),default='observed')
    args=parser.parse_args(); out=R.local(args.out)
    started=time.monotonic()
    shape=None if args.reading_shape=='observed' else balanced_shape()
    try:
        rows=evaluate(args.n_rep,args.n_boot,args.n_docs,args.seed,shape=shape,progress=lambda s:print(s,flush=True))
    except ValueError as error:
        guard=R.DiskGuard(work=out.parent); guard.mkdir(out.parent)
        failure=dict(status='stopped',reason=str(error),reading_shape=args.reading_shape,
                     n_rep=args.n_rep,n_boot=args.n_boot,n_docs=args.n_docs,seed=args.seed,
                     panel_draw_audit=getattr(error,'audit',None),retried_draws=0,
                     driver_sha256=R.file_hash(__file__),analysis_sha256=R.file_hash(A.__file__))
        R.write_json(out.with_suffix('.failed.json'),failure,guard)
        print('STOPPED: '+str(error),flush=True)
        raise SystemExit(2)
    guard=R.DiskGuard(work=out.parent); guard.mkdir(out.parent)
    guard.allocation(len(rows)*4000)
    with out.open('w',newline='') as stream:
        writer=csv.DictWriter(stream,fieldnames=list(rows[0]),delimiter='\t'); writer.writeheader(); writer.writerows(rows)
    metadata=dict(schema='conditional-test-document-coverage-v1',n_rep=args.n_rep,n_boot=args.n_boot,n_docs=args.n_docs,
        seed=args.seed,method=A.PANEL_METHOD,nominal=.9,clusters=10,cpu_threads=1,seconds=time.monotonic()-started,
        reading_shape=args.reading_shape,
        n_readings=rows[0]['n_readings'],n_languages=rows[0]['n_languages'],
        requested_draws=sum(row['requested_draws'] for row in rows if row['quantity']=='R_1w'),
        usable_draws=sum(row['usable_draws'] for row in rows if row['quantity']=='R_1w'),
        undefined_draws=sum(row['undefined_draws'] for row in rows if row['quantity']=='R_1w'),
        max_undefined_draws=max(row['max_undefined_draws'] for row in rows),
        unavailable_reading_policy='omit jointly across paired quantities; stop only above 1% per requested panel run; no redraw',
        source_sha256={Path(m.__file__).name:R.file_hash(m.__file__) for m in (A,D)},driver_sha256=R.file_hash(__file__),
        panel_sha256=R.file_hash(D.O.DEFAULT_PANEL),training='fixed correct symmetric binary Markov probability models',
        target='finite latent panel; known expected held-out density with document-start costs',
        limits='Local binary Markov processes, two-syllable words and unequal document sizes; not validated coverage for real corpora, estimator bias, skipped dependencies, or training variation.')
    R.write_json(out.with_suffix('.json'),metadata,guard)
    print(f'coverage rows={len(rows)} replicates_per_cell={args.n_rep} panel_draws={args.n_boot} seconds={metadata["seconds"]:.3f} cpu_threads=1',flush=True)

if __name__=='__main__':
    main()
