"""Expanded §4b panel coverage on invented two-type Markov corpora with known densities.

Fixed correct scorers; unequal document sizes, two-syllable words, stationary
document starts and language-specific flip probabilities. Token losses are
shared across rungs; aligned/independent source documents and training-plugin
columns are explicit simulation settings. Rung 4 has no extra information beyond
1 in this local Markov family. This does not replace F3b's estimator-bias checks.
The known conditional density is cross-entropy under the frozen scorer, not an
oracle substituted for a finite test sample. Reading noise uses the shape-only
resource and the already declared 'data' settings. No fit, GPU or real text.
"""
